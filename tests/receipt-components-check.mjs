import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { JSDOM } from 'jsdom';
import React, { act } from 'react';
import { seedState, createLoan, dayOffset, defaultSettings } from '../app/domain.ts';
import { receiptContent } from '../app/receipt-model.ts';

// Isolated component test: no web server, network, login, real records or messages.
const dom = new JSDOM('<!doctype html><div id="root"></div>', { url: 'https://elo.example', pretendToBeVisual: true });
const { window } = dom;
for (const key of ['window', 'document', 'HTMLElement', 'HTMLInputElement', 'HTMLButtonElement', 'SVGElement', 'Element', 'Node', 'NodeFilter', 'MutationObserver', 'CustomEvent', 'Event', 'FormData']) globalThis[key] = key === 'window' ? window : window[key];
Object.defineProperty(globalThis, 'navigator', { configurable: true, value: window.navigator });
globalThis.self = window;
globalThis.getComputedStyle = window.getComputedStyle.bind(window);
globalThis.requestAnimationFrame = window.requestAnimationFrame.bind(window);
globalThis.cancelAnimationFrame = window.cancelAnimationFrame.bind(window);
globalThis.IS_REACT_ACT_ENVIRONMENT = true;
globalThis.ResizeObserver = class { observe() {} unobserve() {} disconnect() {} };
const { createRoot } = await import('react-dom/client');
const { default: PieceForm } = await import('../app/piece-form.tsx');
const { default: ReceiptDialog } = await import('../app/receipt.tsx');
const { default: Portal } = await import('../app/portal/portal.tsx');
const root = createRoot(document.getElementById('root'));
const button = name => [...document.querySelectorAll('button')].find(element => element.textContent === name);
const tick = () => new Promise(resolve => setTimeout(resolve, 10));
async function ready() { for (let index = 0; index < 100; index++) { if (button('Baixar PDF')?.disabled === false) return; await act(tick); } throw Error('PDF did not become ready'); }
try {
  let piece;
  await act(async () => root.render(React.createElement(PieceForm, { piece: 'new', pieces: [], onClose() {}, onSave(value) { piece = value; } })));
  assert.equal(document.querySelectorAll('form [required]').length, 0);
  const form = document.querySelector('form');
  assert.equal(form.checkValidity(), true);
  await act(async () => form.dispatchEvent(new window.Event('submit', { bubbles: true, cancelable: true })));
  assert.ok(piece);
  assert.deepEqual([piece.name, piece.sku, piece.available, piece.value], ['', '', 0, 0]);
  const state = seedState();
  const merchant = state.merchants[0];
  const assistance = state.settings || defaultSettings;
  const { loan } = createLoan(state, merchant.id, dayOffset(3), { p1: 2 }, 'Fixture only');
  let signature;
  const props = { loan, merchant, assistance, onClose() {}, async onSign(value) { signature = value; return true; } };
  await act(async () => root.render(React.createElement(ReceiptDialog, props)));
  await ready();
  assert.equal(button('Salvar assinatura').disabled, true);
  const svg = document.querySelector('.signature-pad svg');
  svg.getBoundingClientRect = () => ({ left: 0, top: 0, width: 1000, height: 400 });
  svg.setPointerCapture = () => {};
  const pointer = (type, x, y) => svg.dispatchEvent(new window.PointerEvent(type, { pointerId: 1, button: 0, clientX: x, clientY: y, bubbles: true, cancelable: true }));
  await act(async () => { pointer('pointerdown', 50, 250); pointer('pointermove', 150, 100); pointer('pointermove', 280, 270); pointer('pointerup', 280, 270); });
  assert.equal(button('Salvar assinatura').disabled, false);
  await act(async () => document.querySelector('.receipt-sign-form').dispatchEvent(new window.Event('submit', { bubbles: true, cancelable: true })));
  assert.deepEqual(signature.strokes, [[[50, 250], [150, 100], [280, 270]]]);
  assert.equal(signature.receiptFingerprint, createHash('sha256').update(JSON.stringify(receiptContent(loan, merchant, assistance))).digest('hex'));
  // A concurrently changed document must discard the old handwriting before saving.
  await act(async () => root.render(React.createElement(ReceiptDialog, { ...props, loan: { ...loan, notes: 'Changed by another operation' } })));
  assert.equal(document.querySelectorAll('.signature-pad polyline').length, 0);
  assert.equal(button('Salvar assinatura').disabled, true);
  await ready();
  let shared;
  navigator.canShare = ({ files }) => files.length === 1 && files[0].type === 'application/pdf';
  navigator.share = async value => { shared = value; };
  const signedLoan = { ...loan, receipt: { ...receiptContent(loan, merchant, assistance), signature: { name: signature.signerName, strokes: signature.strokes, at: new Date().toISOString() } } };
  await act(async () => root.render(React.createElement(ReceiptDialog, { ...props, loan: signedLoan })));
  await ready();
  assert.equal(document.querySelector('.receipt-sign-form'), null);
  assert.ok(document.querySelector('.receipt-signed'));
  await act(async () => button('Compartilhar PDF / WhatsApp').click());
  assert.equal(shared.files.length, 1);
  assert.match(shared.files[0].name, /-assinado\.pdf$/);
  assert.equal(shared.files[0].type, 'application/pdf');
  assert.ok(shared.files[0].size > 1000);
  navigator.canShare = () => false;
  await act(async () => root.render(React.createElement(ReceiptDialog, { ...props, loan: signedLoan, onSign: undefined })));
  assert.equal(button('Compartilhar PDF / WhatsApp'), undefined);
  assert.ok(button('Baixar PDF'));
  assert.match(document.querySelector('a[href^="https://wa.me/"]').href, /text=/);
  const requests = [];
  globalThis.fetch = async (url, options) => { requests.push({ url, method: options?.method || 'GET' }); return Response.json({ revision: 1, actor: { name: 'Partner', email: 'partner@example.com' }, merchant, assistance, loans: [signedLoan], notices: [], receivables: [], payments: [] }); };
  await act(async () => root.render(React.createElement(Portal)));
  assert.equal(requests.length, 1);
  assert.equal(requests[0].method, 'GET');
  assert.match(document.body.textContent, /Meus empréstimos/);
  assert.doesNotMatch(document.body.textContent, /Confirmar recebimento|Contestar|Solicitar prazo|Avisar devolução/);
  assert.ok(button('Ver comprovante assinado'));
  console.log('OK: optional form submission, pointer signature, stale document reset, immutable signed view, prepared PDF native sharing/fallback and read-only portal. All interactions and sharing isolated/mocked.');
} finally { await act(async () => root.unmount()); dom.window.close(); }
